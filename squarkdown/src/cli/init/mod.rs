fn write_squarkup_toml(config: &str, cwd: &Path) -> io::Result<()>
{
	out!();
	out!("Writing your {B}squarkup.toml...");

	fs::write(path!(cwd / "squarkup.toml"), config.as_bytes())?;
	
	print!("{PREV}{CLEAR}");
	out!("{GREY}Wrote your squarkup.toml!");

	Ok(())
}
